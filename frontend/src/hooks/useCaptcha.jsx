import { useCallback, useEffect, useId, useRef, useState } from 'react';
import Icon from '../components/ui/Icon.jsx';
import { getCaptcha } from '../api/client.js';

// Self-hosted security check on the public forms (register, forgot password, resend verification,
// "Leave us a message", "Notify me"): the server draws a distorted 5-digit code and checks the answer.
// When the server has it switched off (CAPTCHA_ENABLED=false), nothing is rendered or sent.

/**
 * const captcha = useCaptcha();
 *   {captcha.element}                        render inside the form, above the submit button
 *   const extra = await captcha.payload();   { captchaId, captchaAnswer } to send, or {} when off (throws if empty)
 *   captcha.reset()                          after a successful submit: each code works once
 *   captcha.fail(err)                        after a failed submit: new code unless only a form field was wrong
 */
export function useCaptcha() {
  const [challenge, setChallenge] = useState(null); // { enabled, id, image } | null while loading
  const [answer, setAnswer] = useState('');
  const [error, setError] = useState('');
  const [loadError, setLoadError] = useState('');
  const first = useRef(null);
  const inputRef = useRef(null);
  const inputId = useId();

  const load = useCallback(() => {
    setLoadError('');
    const p = getCaptcha()
      .then((c) => {
        setChallenge(c);
        setAnswer('');
        return c;
      })
      .catch(() => {
        setLoadError("The security code couldn't load.");
        return null;
      });
    return p;
  }, []);

  useEffect(() => {
    first.current = load();
  }, [load]);

  const payload = useCallback(async () => {
    const c = challenge || (await first.current);
    if (!c) {
      const msg = "The security code couldn't load. Click the refresh button, then try again.";
      setError(msg);
      throw new Error(msg);
    }
    if (!c.enabled) return {};
    const digits = answer.replace(/\D/g, '');
    if (digits.length < (c.length || 5)) {
      const msg = 'Please type the numbers shown in the security check.';
      setError(msg);
      inputRef.current?.focus();
      throw new Error(msg);
    }
    setError('');
    return { captchaId: c.id, captchaAnswer: digits };
  }, [challenge, answer]);

  const reset = useCallback(() => {
    setError('');
    if (challenge?.enabled !== false) load();
  }, [challenge, load]);

  const fail = useCallback(
    (err) => {
      // 422 = a form field was wrong: the code wasn't checked yet, so keep it and what was typed.
      if (err?.status === 422 && err?.fields?.reason !== 'captcha') return;
      if (err?.fields?.reason === 'captcha') setError(err.fields.captcha || err.message);
      if (challenge?.enabled !== false) load();
    },
    [challenge, load]
  );

  const refresh = () => {
    setError('');
    load();
    inputRef.current?.focus();
  };

  const enabled = challenge ? challenge.enabled : true; // assume on until the server says otherwise
  const element = enabled ? (
    <div className={`captcha${error ? ' has-error' : ''}`}>
      <label className="captcha__label" htmlFor={inputId}>
        <Icon name="shield" size={14} /> Security check
      </label>
      <div className="captcha__row">
        <span className="captcha__img" aria-hidden="true">
          {challenge?.image ? (
            // The SVG is generated by our own server (no user input); its digits are paths, not text.
            <span dangerouslySetInnerHTML={{ __html: challenge.image }} />
          ) : (
            <span className="captcha__placeholder">{loadError ? 'Not loaded' : 'Loading…'}</span>
          )}
        </span>
        <button type="button" className="captcha__refresh" onClick={refresh} aria-label="Show a new code" title="Show a new code">
          <Icon name="refresh" size={17} />
        </button>
        <input
          ref={inputRef}
          id={inputId}
          className="captcha__input"
          type="text"
          inputMode="numeric"
          autoComplete="off"
          maxLength={challenge?.length || 5}
          placeholder="Enter code"
          aria-invalid={Boolean(error)}
          aria-describedby={error ? `${inputId}-error` : undefined}
          value={answer}
          onChange={(e) => {
            setAnswer(e.target.value.replace(/\D/g, ''));
            if (error) setError('');
          }}
        />
      </div>
      {(error || loadError) && (
        <p id={`${inputId}-error`} className="captcha__error" role="alert">{error || `${loadError} Click the refresh button.`}</p>
      )}
    </div>
  ) : null;

  return { enabled: Boolean(enabled), element, payload, reset, fail };
}
